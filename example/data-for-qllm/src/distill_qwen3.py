"""
distill_qwen3.py
Distill datasets using Qwen/Qwen3-0.6B as the teacher model.

For each example, every assistant turn is regenerated by the model given the
conversation history up to that point (with previously distilled assistant
responses used as context). Single-turn and multi-turn conversations are both
supported.

Usage:
    python distill_qwen3.py --all                        # distill all datasets
    python distill_qwen3.py --data ii_7M_instruct.jsonl  # distill one dataset
    python distill_qwen3.py --all --sample 10            # distill 10 examples each
    python distill_qwen3.py --data task_0.2M_instruct.jsonl --sample 1  # test run
"""

import argparse
import json
import os
import sys

import torch
from tqdm import tqdm
from transformers import AutoModelForCausalLM, AutoTokenizer

# Input filename -> output filename (relative to the data directory)
FILE_MAPPING = {
    "ii_7M_instruct.jsonl": "ii_7M_instruct_distill.jsonl",
    "ii_gen_1.4M_instruct.jsonl": "ii_gen_1.4M_instruct_distill.jsonl",
    "tulu_0.6M_instruct.jsonl": "tulu_distill.jsonl",
    "am_1.4M_instruct.jsonl": "am_1.4M_instruct_distill.jsonl",
    "task_0.2M_instruct.jsonl": "task_0.2M_instruct_distill.jsonl",
    "ii_1.5M_base.jsonl": "ii_1.5M_base_distill.jsonl",
}

VALID_DATASETS = list(FILE_MAPPING.keys())
MODEL_NAME = "Qwen/Qwen3-0.6B"


def load_model(model_name: str = MODEL_NAME):
    print(f"Loading model: {model_name}")
    tokenizer = AutoTokenizer.from_pretrained(model_name, trust_remote_code=True)
    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        torch_dtype=torch.float16,
        device_map="auto",
        trust_remote_code=True,
    )
    model.eval()
    print(f"  Model loaded. Device: {model.device}")
    return model, tokenizer


def generate_response(model, tokenizer, messages: list) -> str:
    """Feed conversation history to the model and return the generated response.
    messages must end with a user turn; the model's continuation is returned."""
    text = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
        enable_thinking=False,
    )
    inputs = tokenizer(text, return_tensors="pt").to(model.device)
    with torch.no_grad():
        # Recommended gen configurations from Qwen team for best quality (instruct mode)
        outputs = model.generate(
            **inputs,
            max_new_tokens=1024,
            do_sample=True,
            temperature=0.7,
            top_p=0.95,
            top_k=20,
            min_p=0.0,
            pad_token_id=tokenizer.eos_token_id,
        )
    generated_ids = outputs[0][inputs.input_ids.shape[1]:]
    response = tokenizer.decode(generated_ids, skip_special_tokens=True)
    return response


def distill_example(model, tokenizer, messages: list) -> list:
    """
    Distill a single conversation.

    Each assistant turn is regenerated by the model. Previously distilled
    assistant responses are used as context for subsequent turns.
    """
    distilled = []
    for msg in messages:
        if msg["role"] == "assistant":
            response = generate_response(model, tokenizer, distilled)
            distilled.append({"role": "assistant", "content": response})
        else:
            distilled.append(msg.copy())
    return distilled


def process_file(model, tokenizer, input_path: str, output_path: str, sample: int = 0):
    """
    Process a single JSONL file.
    If sample > 0, only process the first N examples.
    """
    print(f"\n{'=' * 60}")
    print(f"Input:  {input_path}")
    print(f"Output: {output_path}")

    if not os.path.exists(input_path):
        print(f"  ERROR: Input file not found: {input_path}")
        print(f"  Skipping. Run data_prepare.sh --data first to generate it.")
        return

    total = sum(1 for _ in open(input_path, "r", encoding="utf-8"))
    if sample and sample > 0:
        total = min(total, sample)
        print(f"  Sample mode: processing {total} examples")
    else:
        print(f"  Processing all {total} examples")

    processed = 0
    skipped = 0
    with open(output_path, "w", encoding="utf-8") as fout:
        with open(input_path, "r", encoding="utf-8") as fin:
            pbar = tqdm(total=total, desc="  Distilling")
            for i, line in enumerate(fin):
                if sample and sample > 0 and processed >= sample:
                    break
                line = line.strip()
                if not line:
                    continue
                try:
                    example = json.loads(line)
                except json.JSONDecodeError:
                    skipped += 1
                    continue

                messages = example.get("messages")
                if not messages or not isinstance(messages, list):
                    skipped += 1
                    continue

                distilled_msgs = distill_example(model, tokenizer, messages)
                fout.write(json.dumps({"messages": distilled_msgs}, ensure_ascii=False) + "\n")
                processed += 1
                pbar.update(1)
            pbar.close()

    size_mb = os.path.getsize(output_path) / 1024 / 1024
    print(f"  Done: {processed} examples (skipped: {skipped}) -> {output_path} ({size_mb:.1f} MB)")


def main():
    parser = argparse.ArgumentParser(
        description="Distill datasets using Qwen/Qwen3-0.6B"
    )
    parser.add_argument(
        "--data_dir",
        type=str,
        default="/path/to/",
        help="Directory containing input JSONL files and where output is written. "
             "Defaults to /path/to/.",
    )
    parser.add_argument(
        "--data",
        type=str,
        default=None,
        help=f"Dataset name to distill (e.g. ii_7M_instruct.jsonl). "
             f"Valid options: {VALID_DATASETS}",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        default=False,
        help="Distill all datasets in FILE_MAPPING.",
    )
    parser.add_argument(
        "--sample",
        type=int,
        default=0,
        help="Only distill the first N examples from each file (0 = process all).",
    )
    parser.add_argument(
        "--model",
        type=str,
        default=MODEL_NAME,
        help=f"Model name (default: {MODEL_NAME})",
    )
    args = parser.parse_args()

    # Resolve data directory
    data_dir = os.path.abspath(args.data_dir)

    print(f"Data directory: {data_dir}")

    # Determine which datasets to process
    if args.data:
        if args.data not in FILE_MAPPING:
            print(f"Error: Invalid dataset '{args.data}'.")
            print(f"Valid options: {VALID_DATASETS}")
            sys.exit(1)
        to_process = {args.data: FILE_MAPPING[args.data]}
    elif args.all:
        to_process = dict(FILE_MAPPING)
    else:
        # Default: process all
        to_process = dict(FILE_MAPPING)

    print(f"Datasets to distill: {list(to_process.keys())}")
    if args.sample > 0:
        print(f"Sample mode: {args.sample} example(s) per dataset")

    # Load model once
    model, tokenizer = load_model(args.model)

    # Process each dataset
    for input_name, output_name in to_process.items():
        input_path = os.path.join(data_dir, input_name)
        output_path = os.path.join(data_dir, output_name)
        process_file(model, tokenizer, input_path, output_path, args.sample)

    print(f"\n{'=' * 60}")
    print("Distillation complete.")
    for _, output_name in to_process.items():
        output_path = os.path.join(data_dir, output_name)
        if os.path.exists(output_path):
            lines = sum(1 for _ in open(output_path, "r", encoding="utf-8"))
            size_mb = os.path.getsize(output_path) / 1024 / 1024
            print(f"  {output_name}: {lines} examples ({size_mb:.1f} MB)")
        else:
            print(f"  {output_name}: NOT GENERATED")


if __name__ == "__main__":
    main()
